#!/usr/bin/env python3
"""Write the migration that carries a data change to databases already seeded.

    python3 -I scripts/materials/diff_migration.py <old data dir> [out.sql]

Builds the rows twice, from the old copy of data/materials and from the
current one (the same build_seed.py code the full seed uses), and writes one
UPDATE per changed column, one for availability and one that retires photos
the data no longer lists. Rows are matched by brand, model, variant and size
(ids differ in production); only system-catalogue rows nobody edited
(updated_by IS NULL) are touched. Photos are retired the way 0076 did it:
status 'removed', file cleared, the media sweeper deletes the file.
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import build_seed as B  # noqa: E402

IDENT = ("category", "brand", "model", "variant", "size")
SKIP = {"images", "notes"}


def built(data_dir):
    """identity -> (row, availability record or None) for a data directory."""
    B.DATA = data_dir
    with open(os.path.join(data_dir, "availability.json"), encoding="utf-8") as fh:
        research = {(r["brand"].lower(), r["model"].lower(), (r["variant"] or "").lower()): r
                    for r in json.load(fh)}
    out = {}
    for name, make in (("kayaks", B.kayak), ("paddles", B.paddle)):
        with open(os.path.join(data_dir, name + ".json"), encoding="utf-8") as fh:
            raw = json.load(fh)
        for orig in raw:
            r = research[(orig["brand"].lower(), orig["model"].lower(), (orig.get("variant") or "").lower())]
            for e in B.split_paddles([orig]) if name == "paddles" else [orig]:
                row = make(e)
                row["editor_note"], row["notes"] = row["notes"], None
                out[tuple((row[c] or "").lower() for c in IDENT)] = (row, r)
    return out


def ident(row):
    return {c: row[c] for c in IDENT}


def render(old_dir):
    old, new = built(old_dir), built(os.path.join(B.ROOT, "data", "materials"))
    if set(old) != set(new):
        raise SystemExit(f"row set changed: {sorted(set(old) ^ set(new))[:5]}")
    by_col, avail, photos = {}, [], []
    for key, (row, ar) in new.items():
        orow, oar = old[key]
        for c in B.COLUMNS:
            if c in IDENT or c in SKIP or row.get(c) == orow.get(c):
                continue
            by_col.setdefault(c, []).append({**ident(row), "val": row.get(c)})
        if (ar["status"], ar["source"]) != (oar["status"], oar["source"]):
            avail.append({**ident(row), "availability": ar["status"], "availability_source": ar["source"]})
        was = {i["url"] for i in orow["images"]}
        now = {i["url"] for i in row["images"]}
        photos += [{**ident(row), "url": u} for u in sorted(was - now)]
    match = """WHERE m.category = v.category
  AND lower(btrim(m.brand)) = lower(btrim(v.brand))
  AND lower(btrim(m.model)) = lower(btrim(v.model))
  AND lower(btrim(COALESCE(m.variant, ''))) = lower(btrim(COALESCE(v.variant, '')))
  AND lower(btrim(COALESCE(m.size, ''))) = lower(btrim(COALESCE(v.size, '')))
  AND m.created_by = 'system-catalogue'"""
    ident_defs = "category material_category, brand text, model text, variant text, size text"

    def payload(rows):
        text = json.dumps(rows, ensure_ascii=False, separators=(",", ":"))
        if "$fix$" in text:
            raise SystemExit("payload contains the dollar-quote tag")
        return "$fix$" + text + "$fix$"

    parts = ["""-- Generated by scripts/materials/diff_migration.py from the change to
-- data/materials/*.json: Playak values confirmed or corrected against the
-- maker, quality-review fixes, availability without maker proof reset to
-- unknown, doubtful photos retired, construction without a source cleared.
-- Rows are matched by brand, model, variant and size (ids differ in
-- production). Only system-catalogue rows nobody edited (updated_by) are
-- changed; photos are retired for any catalogue row.
"""]
    for c in B.COLUMNS:
        if c not in by_col:
            continue
        parts.append(f"""-- {c}: {len(by_col[c])} rows
UPDATE materials m SET {c} = v.val, updated_at = NOW()
FROM jsonb_to_recordset({payload(by_col[c])}::jsonb) AS v({ident_defs}, val {B.sql_type(c)})
{match}
  AND m.updated_by IS NULL
  AND m.{c} IS DISTINCT FROM v.val;
""")
    if avail:
        parts.append(f"""-- availability: {len(avail)} rows
UPDATE materials m SET availability = v.availability,
    availability_source = v.availability_source
FROM jsonb_to_recordset({payload(avail)}::jsonb) AS v({ident_defs},
    availability material_availability, availability_source text)
{match}
  AND m.updated_by IS NULL
  AND (m.availability, m.availability_source)
      IS DISTINCT FROM (v.availability, v.availability_source);
""")
    if photos:
        parts.append(f"""-- photos: {len(photos)} retired
UPDATE material_images i SET status = 'removed', file = NULL
FROM materials m
JOIN jsonb_to_recordset({payload(photos)}::jsonb) AS v({ident_defs}, url text) ON TRUE
{match}
  AND i.material_id = m.id AND i.source_url = v.url
  AND i.source_kind <> 'user' AND i.status <> 'removed';
""")
    summary = {c: len(r) for c, r in by_col.items()}
    print(summary, "availability:", len(avail), "photos:", len(photos), file=sys.stderr)
    return "\n".join(parts)


def main():
    sql = render(os.path.abspath(sys.argv[1]))
    if len(sys.argv) > 2:
        with open(sys.argv[2], "w", encoding="utf-8") as fh:
            fh.write(sql)
    else:
        sys.stdout.write(sql)


if __name__ == "__main__":
    main()
